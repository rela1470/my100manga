-- タグで言えるようになったシリーズ名の修正を外す（db/MIGRATIONS.md の台帳に記録すること）。
--
-- 下記 13 件の series_name_override は、レーベル/シリーズのタグ（label_tag / series_tag,
-- db/add-label-tag.sql, db/add-series-tag.sql）が無かった頃に、版の違いをシリーズ名そのものへ
-- 書き込んで区別していたもの。タグができた今はカードにも巻一覧にも「廉価版」「文庫版」「傑作選」
-- のバッジが出るので、修正名は同じことを二重に言っている。外すと表示名はマスターの名前
-- （series.name_display → series.name、src/util.ts seriesNameSql）に戻り、区別はバッジが担う。
--
-- 外すのは **有効なタグが付いていて、かつ修正名がそのタグと同じ内容しか足していない** 行だけ。
-- 編名・部番号（ドラゴンボールZ 各編、ジョジョ Part 1〜9、金田一 第Ⅰ/Ⅱ期）、海外版、
-- マスタ破損の修正（C312117「ｖ」→ハレグゥ、G9784088511818 Dr.スランプ）は残す。
-- C275066 もタグは傑作選だが、修正名が同時に ドラゴンボールZ → ドラゴンボール の書名修正を
-- 兼ねていて、外すと C275075 と同じカードになるので残す。
--
-- 注意 1: 修正名は検索の照合にも使っている（db/add-name-override-search.sql）。外すとその
-- 名前での引き当ても消えるが、ここの 13 件は「金田一少年の事件簿 廉価版」のような誰も打たない
-- 文字列なので実害は無い。マスタの書名が壊れていて修正名でしか引けないシリーズは上記のとおり除外。
--
-- 注意 2: C259229（ゴルゴ13 / My first big）は、外すと同じく廉価版タグの C260140
-- （My first big super, 3巻）とカードの見出しが「ゴルゴ13［廉価版］」で並ぶ。ただし曖昧判定
-- （public/app.js ambiguousEditionKeys）が効くので、メタ行にレーベルと初版年が出て区別できる。
-- 鍵に使う作者は series.creators ではなく **先頭の巻の creators**（src/search.ts SERIES_COLS の
-- COALESCE 副問い合わせ）で、この 2 件はどちらも「さいとう・たかを、さいとう・プロ」で一致する。
-- 適用後の本番 /api/search で、C259229 が「My first big」・C260140 が「My first big super」と
-- 出ることを確認済み。
--
-- 以後の個別の取り消しは管理画面から行える
-- （「シリーズ名の修正」→「修正した名前を表示」→「修正を外す」、src/admin.ts
-- adminDeleteNameOverride）。この SQL はまとめて 13 件を片付けるための一回限りのもの。

