-- series.version: シリーズの版表示（MADB の schema:version）。
--
-- MADB は同じ作品の版違いを「同じ schema:name の別 C-id」として持つ。例えば横山光輝
-- 「三国志」は潮出版社だけで 8 シリーズあり、マスタの名前はどれも「三国志」:
--   C276805 希望コミックス 全60巻 (1974) / C276801 潮漫画文庫 全30巻 (1997) /
--   C276817 Kibo comics 全24巻 (2004) / C276797 全30巻 (2007) /
--   C367640 全21巻 (2017) / C433383 Kibo comics:カジュアルワイド 全11巻 (2019) ほか
-- 検索するとこれが「三国志」のカード 8 枚として並び、どれが何版か分からなかった。
--
-- 版を区別できるマスタの情報は schema:version だけで（13.9 万シリーズ中 3,923 件が持つ。
-- 新装版 859 / コミック版 442 / 完全版 408 / 愛蔵版 274 / 新版 152 / 改訂版 125 / 大判 15 …）、
-- 取り込みがこれを読んでいなかった。上の例では C367640 が「大判」、C276817 が
-- 「カジュアルワイド」、C433383 が「改訂版」を持つ。楽天ブックス・openBD にも版表示は
-- 無く（実測。openBD は 2017 年版の書名が「大判三国志」になっているだけ）、schema:version が
-- 唯一の自動ソース。これでも版表示を持たない行（上の 2007 年版 = 愛蔵版）は残るので、
-- 表示側は版表示 →（同名が並ぶときだけ）レーベル・初版年、の順で区別する（src/search.ts）。
--
-- 表示専用。検索の照合は今までどおり name_norm / name_kana_norm に対して行う。
--
-- 中身は取り込み直し（scripts/ingest.mjs）で埋まる。この ALTER は、取り込みが series を
-- 作り直すまでのあいだ、列を参照するクエリ（src/search.ts / src/series.ts）が動くように
-- するためのもの。デプロイの前に流す。
ALTER TABLE series ADD COLUMN version TEXT;
