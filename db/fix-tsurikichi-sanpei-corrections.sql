-- 2026-10-05 C326076『釣りキチ三平』(講談社コミックス) の手動追加 13 件を取り消す。
--
-- 中身はすべて KCスペシャル版 (1986-87) の ISBN で、別シリーズ C328178 の巻そのもの。
-- 講談社コミックス版の 12〜25 巻として追加されていたが、版が違う ＝ 同じ本が 2 つのシリーズに
-- 重複して並ぶ状態だった。穴埋め (src/gapFill.ts) には「master が既に持つ ISBN はどのシリーズの
-- ものでも採らない」規則があるが、手動追加 (src/corrections.ts addCorrection) は書影の有無しか
-- 見ていないので、この経路から入った。
--
-- 12・13・14・15・17・18・19・23 巻は 2026-10-05 の Yahoo 穴埋め (ca7bf12) で講談社コミックス版の
-- 正しい ISBN が入ったので、消すと正しい方だけが残る。20・21・22・24・25 巻は講談社コミックス版の
-- ISBN がどの情報源にも無いので、消すと「ISBN が見つかりませんでした」に戻る。
--
-- 本番にだけ存在する（dev / R18 2 環境には 0 件）。
DELETE FROM series_correction
 WHERE series_id = 'C326076'
   AND isbn IN (
     '9784061011847', -- 12 巻として追加 / 実体は KCスペシャル 12
     '9784061011854', -- 13 /  KCスペシャル 第13集
     '9784061011861', -- 14 /  KCスペシャル 第14集
     '9784061012318', -- 15 /  KCスペシャル 第15集
     '9784061012332', -- 17 /  KCスペシャル 17
     '9784061012349', -- 18 /  KCスペシャル 18
     '9784061012356', -- 19 /  KCスペシャル 19
     '9784061012363', -- 20 /  KCスペシャル 20
     '9784061012370', -- 21 /  KCスペシャル 21
     '9784061012387', -- 22 /  KCスペシャル 22
     '9784061012394', -- 23 /  KCスペシャル 第23集
     '9784061012400', -- 24 /  KCスペシャル 24
     '9784061012790'  -- 25 /  KCスペシャル 第25集
   );

-- 表示データの世代を上げて、巻一覧のエッジキャッシュとリストの閲覧スナップショットを作り直させる
-- (src/viewSnapshot.ts)。admin の更新系 API が成功後にやることを、直接削除したぶん手で行う。
INSERT INTO meta (key, value) VALUES ('view_epoch', CAST(strftime('%s','now') AS TEXT) || '000')
  ON CONFLICT(key) DO UPDATE SET value = excluded.value;
